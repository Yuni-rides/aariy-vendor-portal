const API_KEYS_MOCK: ApiKey[] = [
  {
    id: "key-erp",
    name: "Warehouse ERP sync",
    prefix: "ak_live_7Hq2",
    scopes: ["products:read", "inventory:write", "orders:read"],
    status: "ACTIVE",
    createdAt: "2026-10-14T09:00:00Z",
    lastUsedAt: "2026-11-17T22:10:00Z",
  },
  {
    id: "key-old",
    name: "Old Shopify script",
    prefix: "ak_live_Zp9c",
    scopes: ["products:read"],
    status: "REVOKED",
    createdAt: "2026-09-02T09:00:00Z",
    lastUsedAt: "2026-10-01T10:00:00Z",
    revokedAt: "2026-10-14T09:05:00Z",
  },
];

/**
 * Mock secret. The real secret is generated by the API and only its hash is stored there.
 */
const makeSecret = () => {
  const bytes = new Uint8Array(24);
  crypto.getRandomValues(bytes);
  const body = Array.from(bytes, (b) => "abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"[b % 57]).join("");
  return `ak_live_${body}`;
};

type ApiKeysStore = {
  loading: boolean;
  saving: boolean;
  error: string | null;
  loaded: boolean;
  keys: ApiKey[];

  fetchKeys: () => Promise<void>;
  createKey: (name: string, scopes: ApiScope[]) => Promise<ApiKeyResult>;
  rotateKey: (id: string) => Promise<ApiKeyResult>;
  revokeKey: (id: string) => Promise<ApiKeyResult>;
};

export const MAX_ACTIVE_KEYS = 5;

export const useApiKeysStore = create<ApiKeysStore>((set, get) => ({
  loading: false,
  saving: false,
  error: null,
  loaded: false,
  keys: [],

  fetchKeys: async () => {
    if (get().loaded) return;
    set({ loading: true, error: null });
    try {
      set({ keys: API_KEYS_MOCK, loading: false, loaded: true });
    } catch (e: any) {
      set({ error: e?.response?.data?.message ?? "Something went wrong", loading: false });
    }
  },

  // TODO(api): POST /v1/seller/api-keys { name, scopes } -> { key, secret }
  createKey: async (rawName, scopes) => {
    const name = rawName.trim();
    if (!name) return { success: false, message: "Give the key a name." };
    if (scopes.length === 0) return { success: false, message: "Pick at least one permission." };
    if (get().keys.filter((k) => k.status === "ACTIVE").length >= MAX_ACTIVE_KEYS)
      return { success: false, message: `You can have up to ${MAX_ACTIVE_KEYS} active keys. Revoke one first.` };
    set({ saving: true });
    const secret = makeSecret();
    const key: ApiKey = {
      id: `key-${Date.now()}`,
      name,
      prefix: secret.slice(0, 12),
      scopes,
      status: "ACTIVE",
      createdAt: new Date().toISOString(),
      lastUsedAt: null,
    };
    set({ keys: [key, ...get().keys], saving: false });
    return { success: true, message: "Key created.", secret: { keyId: key.id, name, secret } };
  },

  // TODO(api): POST /v1/seller/api-keys/:id/rotate -> new secret; the old one stops working.
  rotateKey: async (id) => {
    const key = get().keys.find((k) => k.id === id);
    if (!key || key.status !== "ACTIVE") return { success: false, message: "Only active keys can be rotated." };
    set({ saving: true });
    const secret = makeSecret();
    set({
      keys: get().keys.map((k) => (k.id === id ? { ...k, prefix: secret.slice(0, 12), createdAt: new Date().toISOString() } : k)),
      saving: false,
    });
    return { success: true, message: "Key rotated. The old secret no longer works.", secret: { keyId: id, name: key.name, secret } };
  },

  // TODO(api): DELETE /v1/seller/api-keys/:id (rejected by the API within one minute, SOW 6.3)
  revokeKey: async (id) => {
    const key = get().keys.find((k) => k.id === id);
    if (!key || key.status !== "ACTIVE") return { success: false, message: "This key is already revoked." };
    set({
      keys: get().keys.map((k) => (k.id === id ? { ...k, status: "REVOKED", revokedAt: new Date().toISOString() } : k)),
    });
    return { success: true, message: `"${key.name}" revoked. Apps using it will stop working within a minute.` };
  },
}));
